<script>
export default {
  name: 'HomePage',
  data() {
    return {
      searchQuery: '',
      currentTime: {
        hours: '00',
        minutes: '00',
        seconds: '00'
      },
      timer: null,
      clickCount: 0,
      clickTimer: null,
      showStats: false,
      visitCount: 0,
      todayVisits: 0,
      averageTime: 0,
      visitStartTime: null,
      keySequence: '',
    }
  },
  methods: {
    updateTime() {
      const now = new Date();
      this.currentTime = {
        hours: String(now.getHours()).padStart(2, '0'),
        minutes: String(now.getMinutes()).padStart(2, '0'),
        seconds: String(now.getSeconds()).padStart(2, '0')
      };
    },
    updateStats() {
      const stats = JSON.parse(localStorage.getItem('siteStats') || '{}');
      const today = new Date().toLocaleDateString();
      
      if (!stats.firstVisit) {
        stats.firstVisit = Date.now();
        stats.totalVisits = 0;
        stats.dailyVisits = {};
        stats.totalTime = 0;
      }
      
      stats.totalVisits++;
      stats.dailyVisits[today] = (stats.dailyVisits[today] || 0) + 1;
      
      if (this.visitStartTime) {
        const visitDuration = (Date.now() - this.visitStartTime) / 1000 / 60;
        stats.totalTime += visitDuration;
      }
      
      this.visitCount = stats.totalVisits;
      this.todayVisits = stats.dailyVisits[today] || 0;
      this.averageTime = Math.round(stats.totalTime / stats.totalVisits * 10) / 10;
      
      localStorage.setItem('siteStats', JSON.stringify(stats));
    }
  },
  created() {
    this.updateTime();
    this.timer = setInterval(this.updateTime, 1000);
    this.visitStartTime = Date.now();
    this.updateStats();
    window.addEventListener('beforeunload', this.updateStats);
  },
  beforeDestroy() {
    if (this.timer) {
      clearInterval(this.timer);
    }
    if (this.clickTimer) {
      clearTimeout(this.clickTimer);
    }
    this.updateStats();
    window.removeEventListener('beforeunload', this.updateStats);
  }
}
</script>

